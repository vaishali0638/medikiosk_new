-- 0004 — encounters, pre-check-ins, kiosk sessions, QR nonces and token requests.
--
-- This migration carries the constraints that make duplicate tokens and QR replay
-- structurally impossible rather than merely unlikely. The guarantees are expressed as
-- database constraints, not application checks, because application checks race.

-- Up Migration

CREATE TABLE encounter (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id          uuid NOT NULL REFERENCES patient(id) ON DELETE RESTRICT,
  department_id       uuid NOT NULL REFERENCES department(id) ON DELETE RESTRICT,
  visit_type          visit_type NOT NULL,
  ayush_system        ayush_system,
  -- The HIS's own identifier for this visit. Populated once the HIS acknowledges.
  his_encounter_ref   text,
  -- The final token, exactly as the HIS returned it. Never generated by MediKiosk.
  his_token           text,
  token_issued_at     timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  version             integer NOT NULL DEFAULT 1,
  CONSTRAINT encounter_token_has_timestamp CHECK (
    (his_token IS NULL) = (token_issued_at IS NULL)
  )
);

CREATE INDEX encounter_patient_idx ON encounter (patient_id, created_at DESC);
CREATE INDEX encounter_department_idx ON encounter (department_id, created_at DESC);

CREATE TABLE pre_checkin (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id            uuid NOT NULL REFERENCES patient(id) ON DELETE RESTRICT,
  consent_id            uuid NOT NULL REFERENCES consent(id) ON DELETE RESTRICT,
  hospital_id           uuid NOT NULL REFERENCES hospital(id) ON DELETE RESTRICT,
  branch_id             uuid NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
  department_id         uuid NOT NULL REFERENCES department(id) ON DELETE RESTRICT,
  encounter_id          uuid REFERENCES encounter(id) ON DELETE SET NULL,
  visit_type            visit_type NOT NULL,
  appointment_ref       text,
  visit_window_start    timestamptz NOT NULL,
  visit_window_end      timestamptz NOT NULL,
  state                 pre_checkin_state NOT NULL DEFAULT 'DRAFT',
  submitted_at          timestamptz,
  arrival_confirmed_at  timestamptz,
  -- Which kiosk the patient physically arrived at. Null until they scan.
  arrival_kiosk_id      uuid REFERENCES kiosk_device(id) ON DELETE SET NULL,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  version               integer NOT NULL DEFAULT 1,
  CONSTRAINT pre_checkin_visit_window CHECK (visit_window_end > visit_window_start),
  -- Arrival is a physical event at a kiosk; it cannot be recorded without one.
  CONSTRAINT pre_checkin_arrival_needs_kiosk CHECK (
    (arrival_confirmed_at IS NULL) = (arrival_kiosk_id IS NULL)
  )
);

CREATE INDEX pre_checkin_patient_idx ON pre_checkin (patient_id, created_at DESC);
CREATE INDEX pre_checkin_state_idx ON pre_checkin (state) WHERE state <> 'CONSUMED';

CREATE TABLE kiosk_session (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kiosk_device_id     uuid NOT NULL REFERENCES kiosk_device(id) ON DELETE RESTRICT,
  -- A session starts anonymous; a patient is attached only after identity is confirmed.
  patient_id          uuid REFERENCES patient(id) ON DELETE SET NULL,
  pre_checkin_id      uuid REFERENCES pre_checkin(id) ON DELETE SET NULL,
  state               kiosk_session_state NOT NULL DEFAULT 'CREATED',
  language_tag        text,
  started_at          timestamptz NOT NULL DEFAULT now(),
  last_activity_at    timestamptz NOT NULL DEFAULT now(),
  ended_at            timestamptz,
  -- Records that the secure wipe actually ran, so an incomplete wipe is detectable.
  wiped_at            timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  version             integer NOT NULL DEFAULT 1,
  -- A finished session must have been wiped. This is checked, not assumed.
  CONSTRAINT kiosk_session_ended_is_wiped CHECK (
    state NOT IN ('EXITED', 'EXPIRED') OR wiped_at IS NOT NULL
  )
);

CREATE INDEX kiosk_session_device_idx ON kiosk_session (kiosk_device_id, started_at DESC);
-- Finds sessions eligible for inactivity expiry.
CREATE INDEX kiosk_session_active_idx ON kiosk_session (last_activity_at)
  WHERE ended_at IS NULL;

-- One-time QR references. No medical data is ever placed in a QR code; this table holds
-- the server-side half of the signed reference the patient's phone displays.
CREATE TABLE qr_nonce (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  pre_checkin_id      uuid NOT NULL REFERENCES pre_checkin(id) ON DELETE CASCADE,
  -- The nonce carried in the signed payload. Unique across the whole system.
  nonce               uuid NOT NULL UNIQUE,
  -- Identifies the signing key so keys can be rotated without invalidating history.
  signing_key_id      text NOT NULL,
  state               qr_nonce_state NOT NULL DEFAULT 'ISSUED',
  issued_at           timestamptz NOT NULL DEFAULT now(),
  expires_at          timestamptz NOT NULL,
  consumed_at         timestamptz,
  -- Which kiosk consumed it, for audit.
  consumed_by_kiosk   uuid REFERENCES kiosk_device(id) ON DELETE SET NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT qr_nonce_expiry_after_issue CHECK (expires_at > issued_at),
  CONSTRAINT qr_nonce_consumed_state CHECK (
    (state = 'CONSUMED') = (consumed_at IS NOT NULL)
  )
);

CREATE INDEX qr_nonce_pre_checkin_idx ON qr_nonce (pre_checkin_id, issued_at DESC);
-- A pre-check-in has at most one live QR. Re-issuing must first retire the previous one,
-- which stops two valid codes for the same visit circulating simultaneously.
CREATE UNIQUE INDEX qr_nonce_one_live_per_precheckin
  ON qr_nonce (pre_checkin_id)
  WHERE state = 'ISSUED';

CREATE TABLE token_request (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  pre_checkin_id        uuid NOT NULL REFERENCES pre_checkin(id) ON DELETE RESTRICT,
  encounter_id          uuid REFERENCES encounter(id) ON DELETE RESTRICT,
  kiosk_device_id       uuid NOT NULL REFERENCES kiosk_device(id) ON DELETE RESTRICT,
  -- `<kioskCode>-<preCheckinId>`. THE duplicate-token guard: a retry, a double tap or a
  -- reconnect all derive the same key, so the unique constraint collapses them into one
  -- request. Enforced by the database because an application-level check would race.
  idempotency_key       text NOT NULL UNIQUE CHECK (length(idempotency_key) BETWEEN 8 AND 200),
  state                 token_request_state NOT NULL DEFAULT 'NOT_STARTED',
  attempt_count         integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  -- Token text exactly as returned by the HIS.
  his_token             text,
  his_response_ref      text,
  -- Structured error code from the last failed attempt; never a raw HIS payload.
  last_error_code       text,
  requested_at          timestamptz,
  acknowledged_at       timestamptz,
  issued_at             timestamptz,
  -- Set when a human must check the HIS directly before anything else happens.
  reconciliation_note   text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  version               integer NOT NULL DEFAULT 1,
  CONSTRAINT token_request_issued_has_token CHECK (
    (state = 'ISSUED') = (his_token IS NOT NULL AND issued_at IS NOT NULL)
  )
);

-- A pre-check-in can have at most one issued token, ever. Belt and braces alongside the
-- idempotency key: even a bug that generated a second key could not produce a second
-- issued token for the same visit.
CREATE UNIQUE INDEX token_request_one_issued_per_precheckin
  ON token_request (pre_checkin_id)
  WHERE state = 'ISSUED';

CREATE INDEX token_request_reconciliation_idx ON token_request (created_at)
  WHERE state = 'UNKNOWN_RECONCILIATION_REQUIRED';

CREATE TRIGGER encounter_updated_at BEFORE UPDATE ON encounter
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER pre_checkin_updated_at BEFORE UPDATE ON pre_checkin
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER kiosk_session_updated_at BEFORE UPDATE ON kiosk_session
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER token_request_updated_at BEFORE UPDATE ON token_request
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER encounter_version BEFORE UPDATE ON encounter
  FOR EACH ROW EXECUTE FUNCTION bump_row_version();
CREATE TRIGGER pre_checkin_version BEFORE UPDATE ON pre_checkin
  FOR EACH ROW EXECUTE FUNCTION bump_row_version();
CREATE TRIGGER kiosk_session_version BEFORE UPDATE ON kiosk_session
  FOR EACH ROW EXECUTE FUNCTION bump_row_version();
CREATE TRIGGER token_request_version BEFORE UPDATE ON token_request
  FOR EACH ROW EXECUTE FUNCTION bump_row_version();

-- Down Migration

DROP TABLE IF EXISTS token_request;
DROP TABLE IF EXISTS qr_nonce;
DROP TABLE IF EXISTS kiosk_session;
DROP TABLE IF EXISTS pre_checkin;
DROP TABLE IF EXISTS encounter;
